"""External-effect persistence boundary; facts are committed by the Run kernel."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol
from uuid import UUID


@dataclass(frozen=True)
class EffectInvocationResult:
    state: str
    operation_id: UUID
    result: dict | None = None
    result_ref: str | None = None


class ExecutionEffectStore(Protocol):
    async def list(self, **kwargs) -> list[dict]: ...
    async def get(self, **kwargs) -> dict: ...
    async def existing_request(self, **kwargs) -> dict | None: ...
    async def submit_request(self, **kwargs) -> dict: ...
    async def get_request(self, **kwargs) -> dict: ...
    async def worker_command(self, command, *, preflight=None): ...
    async def claim_request(self) -> dict | None: ...
    async def finish_request(self, row, *, error_code=None, command=None) -> bool: ...
    async def query_count(self, operation_id) -> int: ...
    async def authorize_request(self, row): ...
    async def defer_observation(self, spec, context, observation): ...
    async def projection_work(self, *, limit=20) -> list[dict]: ...
    async def mark_projected(self, operation_id, revision): ...
