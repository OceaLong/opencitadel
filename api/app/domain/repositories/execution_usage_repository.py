from typing import Protocol


class ExecutionUsageRepository(Protocol):
    async def tool_intent_refresh_target(self, scope, run_id, activity_id, subject_digest): ...
    async def tool_intent_refresh_status(self, scope, run_id, activity_id, command_id): ...
    async def approval_subject(self, scope, run_id, approval_id): ...
    async def invocation_authority(self, scope, run_id, *, lock=False) -> dict: ...
    async def authorize_principal(self, scope, principal, *, lock=False) -> None: ...
    async def authorize_tool(
        self, scope, *, skill_id, name, pack, connector_ids, lock=False
    ) -> None: ...
    async def capture_requester(self, scope, authorization, *, run_id) -> dict: ...
    async def snapshot(self, scope, run_id, body, purpose) -> str: ...
    async def admission_snapshot(self, scope, run_id, body, purpose) -> str: ...
    async def load_snapshot(self, scope, run_id, identity, purpose) -> dict: ...

    async def allocate(
        self,
        scope,
        *,
        run_id,
        activity_id,
        generation,
        claim_generation,
        configuration_id,
        request_snapshot,
        logical_group="invoke:0",
    ) -> str: ...
    async def record(self, scope, identity, fact) -> dict: ...
