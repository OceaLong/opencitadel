"""Private caller-transaction budget and deployment policy ports."""

from typing import Protocol

from app.domain.evaluation.budget import BudgetDemand, BudgetPolicy, BudgetSettlement


class EvaluationBudgetRepository(Protocol):
    async def lock_capacity(self, identity: str, demand: BudgetDemand) -> None: ...
    async def reserve(self, identity: str, demand: BudgetDemand) -> dict: ...
    async def settle(self, identity: str, demand: BudgetDemand, fact: BudgetSettlement) -> dict: ...
    async def mark_unknown(self, identity: str, demand: BudgetDemand) -> dict: ...


class EvaluationBudgetPolicyRepository(Protocol):
    async def active(self, *, lock: bool = False) -> BudgetPolicy | None: ...


class EvaluationLineageRepository(Protocol):
    async def get(self, scope, run_id) -> dict | None: ...
    async def assert_current(self, scope, run_id) -> dict: ...
    async def ensure_initial(self, scope, run_id) -> dict: ...
    async def link_replacement(
        self, scope, run_id, *, predecessor_run_id, expected_generation: int
    ) -> dict: ...
