"""Scoped recording persistence owned by its caller's transaction."""

from typing import Protocol

from app.domain.evaluation.recording import RecordingManifest


class EvaluationRecordingRepository(Protocol):
    async def list_jobs(self, scope, *, after=None, limit=51) -> list[dict]: ...
    async def job(self, scope, job_id, *, lock=False) -> dict: ...
    async def create(self, scope, job, selection, principal) -> None: ...
    async def claim(self, scope, job_id, *, now=None): ...
    async def publish(self, scope, manifest: RecordingManifest, token) -> None: ...
    async def version(self, scope, version_id) -> RecordingManifest: ...
    async def binding(self, scope, run_id) -> dict | None: ...
    async def bind(self, scope, run_id, version_id, principal, *, admission=None) -> None: ...
    async def consumed(self, scope, run_id, activity_id) -> dict | None: ...
    async def consume(self, scope, run_id, activity_id, version_id, slot) -> None: ...
    async def fail(self, scope, job_id, token, reason) -> None: ...
    async def require_unadmitted(self, scope, run_id) -> None: ...
    async def capture(self, scope, run_id, activity_id, body) -> None: ...
    async def captured(self, scope, run_id, activity_id) -> dict: ...
    async def object(self, scope, object_id) -> dict: ...
    async def lock_call(self, scope, run_id) -> None: ...
    async def coverage(self, scope, run_id) -> dict: ...
    async def approved(self, scope, run_id, activity_id) -> bool: ...
    async def connector_binding(self, scope, pack, connector_id, *, lock=False) -> str: ...
    async def content_identity(self, scope, run_id, content_id) -> str: ...
