from typing import Protocol
from uuid import UUID

from app.domain.models.scope import OwnerScope, Principal


class EvaluationDatasetRepository(Protocol):
    async def authorize(self, scope: OwnerScope, principal: Principal, *, write: bool) -> None: ...
    async def lock_request(self, scope: OwnerScope, request_id: str) -> None: ...
    async def get_draft(
        self, scope: OwnerScope, dataset_id: UUID, *, lock: bool = False
    ) -> dict: ...
    async def list_versions(
        self, scope: OwnerScope, dataset_id: UUID, *, before: int | None = None, limit: int = 51
    ) -> list[dict]: ...
    async def get_version(self, scope: OwnerScope, version_id: UUID) -> dict: ...
    async def case_members(self, scope: OwnerScope, ids: list[str]) -> list[dict]: ...
    async def list_drafts(self, scope: OwnerScope) -> list[dict]: ...
    async def receipt(
        self, scope: OwnerScope, request_id: str, fingerprint: str
    ) -> dict | None: ...
    async def save_receipt(
        self, scope: OwnerScope, request_id: str, fingerprint: str, result: dict
    ) -> None: ...
    async def lock_object(self, object_id: UUID) -> None: ...
    async def save_import(self, scope: OwnerScope, record: dict) -> None: ...
    async def get_import(
        self, scope: OwnerScope, import_id: UUID, *, lock: bool = False
    ) -> dict: ...
    async def mark_applied(self, scope: OwnerScope, import_id: UUID) -> None: ...
    async def create(self, scope: OwnerScope, dataset_id: UUID, name: str) -> None: ...
    async def replace_cases(
        self, scope: OwnerScope, dataset_id: UUID, cases: list[dict], *, expected_revision: int
    ) -> None: ...
    async def publish(
        self, scope: OwnerScope, dataset_id: UUID, version_id: UUID, *, expected_revision: int
    ) -> dict: ...
    async def certify_analysis(
        self, scope: OwnerScope, principal: Principal, version_id: UUID, resources: tuple
    ) -> None: ...
    async def resources(self, scope: OwnerScope, cases: tuple) -> tuple: ...
